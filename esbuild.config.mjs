import esbuild from "esbuild";
import process from "process";
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import builtins from "builtin-modules";

const root = path.dirname(fileURLToPath(import.meta.url));
const excalidrawDir = path.join(root, "vendor", "excalidraw");
const excalidrawVersion = JSON.parse(fs.readFileSync(path.join(excalidrawDir, "manifest.json"), "utf8")).version;

const banner = `/*
Ink Notebook – an Obsidian plugin built on top of Excalidraw.
This file is generated by esbuild. Source: https://github.com/stefanmayer06/Obsidian-wrighting-for-eink

It includes the unmodified Excalidraw plugin for Obsidian ${excalidrawVersion} by Zsolt Viczian,
licensed under the GNU AGPL v3.0: https://github.com/zsviczian/obsidian-excalidraw-plugin/tree/${excalidrawVersion}
(license text: vendor/excalidraw/LICENSE in the Ink Notebook repository).
*/`;

const prod = process.argv[2] === "production";

/**
 * `import x from "vendored-excalidraw:main.js"` gives the text of a file in
 * vendor/excalidraw (manifest.json as an object). The Excalidraw release is
 * embedded as-is and started by src/obsidian/bundledExcalidraw.ts.
 */
const vendoredExcalidraw = {
  name: "vendored-excalidraw",
  setup(build) {
    build.onResolve({ filter: /^vendored-excalidraw:/ }, (args) => ({
      path: path.join(excalidrawDir, args.path.slice("vendored-excalidraw:".length)),
      namespace: "vendored-excalidraw",
    }));
    build.onLoad({ filter: /.*/, namespace: "vendored-excalidraw" }, (args) => ({
      contents: fs.readFileSync(args.path, "utf8"),
      loader: args.path.endsWith(".json") ? "json" : "text",
      watchFiles: [args.path],
    }));
  },
};

const context = await esbuild.context({
  banner: { js: banner },
  entryPoints: ["src/main.ts"],
  bundle: true,
  plugins: [vendoredExcalidraw],
  external: [
    "obsidian",
    "electron",
    "@codemirror/autocomplete",
    "@codemirror/collab",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/lint",
    "@codemirror/search",
    "@codemirror/state",
    "@codemirror/view",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/lr",
    ...builtins,
  ],
  format: "cjs",
  target: "es2020",
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  minify: prod,
  outfile: "main.js",
});

if (prod) {
  await context.rebuild();
  process.exit(0);
} else {
  await context.watch();
}
