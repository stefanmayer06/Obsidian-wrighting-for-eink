import esbuild from "esbuild";
import process from "process";
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import builtins from "builtin-modules";

const root = path.dirname(fileURLToPath(import.meta.url));

const banner = `/*
Ink Notebook – handwritten notebooks for Obsidian, made for e-ink tablets.
Copyright (C) 2026 Stefan Mayer. Licensed under the GNU AGPL v3.0 or later.
This file is generated by esbuild. Source: https://github.com/stefanmayer06/Obsidian-wrighting-for-eink

The license texts of Ink Notebook and of all third-party code in this file are at its end.
*/`;

const prod = process.argv[2] === "production";

/**
 * The license texts for main.js: Ink Notebook's own and every npm package
 * esbuild bundled (from the metafile). Obsidian
 * installs only main.js, manifest.json and styles.css, so they have to travel
 * inside main.js. A bundled package without a license file fails the build.
 */
function licenseNotices(metafile) {
  const packageDirs = new Set();
  for (const input of Object.keys(metafile.inputs)) {
    const m = /^(.*node_modules\/(?:@[^/]+\/)?[^/]+)\//.exec(input);
    if (m) packageDirs.add(m[1]);
  }
  const sections = [...packageDirs].sort().map((dir) => {
    const pkg = JSON.parse(fs.readFileSync(path.join(root, dir, "package.json"), "utf8"));
    const file = fs.readdirSync(path.join(root, dir)).find((f) => /^(licen[cs]e|copying)(\.(md|txt))?$/i.test(f));
    if (!file) throw new Error(`No license file found for the bundled package ${pkg.name} (${dir})`);
    return { title: `${pkg.name} ${pkg.version} – ${pkg.license}`, text: fs.readFileSync(path.join(root, dir, file), "utf8") };
  });
  sections.unshift({ title: "Ink Notebook – GNU AGPL v3.0", text: fs.readFileSync(path.join(root, "LICENSE"), "utf8") });
  const lines = ["", "// ---------------------------------------------------------------------------", "// License texts: Ink Notebook and the third-party code in this file"];
  for (const { title, text } of sections) {
    lines.push("//", `// ===== ${title} =====`, "//");
    // line comments, so nothing in a license text can end the comment early
    for (const line of text.trimEnd().split(/\r\n|[\n\r\u2028\u2029]/)) lines.push(line ? `// ${line}` : "//");
  }
  return `${lines.join("\n")}\n`;
}

const context = await esbuild.context({
  banner: { js: banner },
  entryPoints: ["src/main.ts"],
  bundle: true,
  external: [
    "obsidian",
    "electron",
    "@codemirror/autocomplete",
    "@codemirror/collab",
    "@codemirror/commands",
    "@codemirror/language",
    "@codemirror/lint",
    "@codemirror/search",
    "@codemirror/state",
    "@codemirror/view",
    "@lezer/common",
    "@lezer/highlight",
    "@lezer/lr",
    ...builtins,
  ],
  format: "cjs",
  target: "es2020",
  logLevel: "info",
  sourcemap: prod ? false : "inline",
  treeShaking: true,
  minify: prod,
  metafile: prod,
  outfile: "main.js",
});

if (prod) {
  const result = await context.rebuild();
  fs.appendFileSync("main.js", licenseNotices(result.metafile));
  process.exit(0);
} else {
  await context.watch();
}
